class LightweightClinicalMatcher:
    def __init__(self, region_dict, triage_dict):
        self.region_keys = list(region_dict.keys())
        self.region_texts = [region_dict[k] for k in self.region_keys]
        self.triage_keys = list(triage_dict.keys())
        self.triage_texts = [triage_dict[k] for k in self.triage_keys]

        self.region_vec = TfidfVectorizer(ngram_range=(1, 3), analyzer="word").fit(self.region_texts)
        self.region_tfidf = self.region_vec.transform(self.region_texts)

        self.triage_vec = TfidfVectorizer(ngram_range=(1, 3), analyzer="word").fit(self.triage_texts)
        self.triage_tfidf = self.triage_vec.transform(self.triage_texts)

    def predict_region(self, patient_text: str):
        normalized = translate_and_normalize_user_turn(patient_text)
        user_vec = self.region_vec.transform([normalized])
        sims = cosine_similarity(user_vec, self.region_tfidf)[0]

        best_tfidf_idx = np.argmax(sims)
        tfidf_score = float(sims[best_tfidf_idx])
        tfidf_region = self.region_keys[best_tfidf_idx]

        best_fuzzy_score, fuzzy_region = 0, "GENERAL"
        for region, kw_text in zip(self.region_keys, self.region_texts):
            score = fuzz.token_set_ratio(normalized, kw_text)
            if score > best_fuzzy_score:
                best_fuzzy_score, fuzzy_region = score, region

        if tfidf_region == fuzzy_region:
            return tfidf_region, (tfidf_score * 0.6 + (best_fuzzy_score / 100.0) * 0.4)
        return (tfidf_region, tfidf_score) if tfidf_score >= (best_fuzzy_score / 100.0) else (fuzzy_region, best_fuzzy_score / 100.0)

    def predict_triage(self, patient_text: str):
        normalized = translate_and_normalize_user_turn(patient_text)
        user_vec = self.triage_vec.transform([normalized])
        sims = cosine_similarity(user_vec, self.triage_tfidf)[0]
        best_idx = np.argmax(sims)
        return self.triage_keys[best_idx], float(sims[best_idx])

