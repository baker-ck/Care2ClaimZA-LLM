def assign_scheme_plan_rules_and_sa_context(row: pd.Series) -> pd.Series:
    spec = str(row["medical_specialty"]).strip()
    desc = str(row["description"]).strip()
    spec_l = spec.lower()
    desc_l = desc.lower()

    # Uniformly Sample a Scheme & Plan Pair
    scheme_key, plan_key, plan_name = random.choice(SCHEME_PLAN_REGISTRY)

    # --- RULE 1: CASH ONLY / UNINSURED ---
    if scheme_key == "Cash_Only_SelfPay":
        decision = "Out-of-Cover"
        treatment = "Direct Patient Cash Self-Pay (No Scheme Cover Applicable)"

    else:
        # --- UNIVERSAL SCHEME EXCLUSIONS (Elective / Cosmetic / Non-Formulary) ---
        out_terms = [
            "autopsy", "lipectomy", "cosmetic", "liposuction", "diet diary", "food diary",
            "supplement", "weight loss", "rhinoplasty", "breast augmentation",
            "bariatric", "tummy tuck", "botox", "chiropractic", "diets and nutritions"
        ]

        if any(t in spec_l or t in desc_l for t in out_terms):
            decision = "Out-of-Cover"
            if "autopsy" in desc_l or "autopsy" in spec_l:
                treatment = f"Post-mortem forensic autopsy examination ({scheme_key} Exclusion)"
            elif any(k in desc_l for k in ["lipectomy", "liposuction", "tummy tuck", "rhinoplasty", "augmentation"]) or "cosmetic" in spec_l:
                treatment = f"Cosmetic plastic surgery / body contouring ({scheme_key} Exclusion)"
            else:
                treatment = f"Non-covered elective/cosmetic healthcare intervention ({scheme_key} Exclusion)"

        # --- PLAN-DIFFERENTIATED POLICY RULES ---
        else:
            is_entry_network_plan = any(k in plan_key for k in ["KeyCare", "BonStart", "Ingwe", "Beat", "flexiFED"])

            if is_entry_network_plan:
                # Entry / Network Plans: Strict PMB Primary Care in-cover at network GP; all specialist/imaging/surgeries require Pre-Auth
                if any(t in desc_l for t in ["upper respiratory", "cold", "flu", "sore throat", "normal physical exam", "well child"]):
                    decision = "In-Cover"
                    treatment = f"{scheme_key} [{plan_key}] Designated Network GP Primary Care Benefit"
                elif any(t in desc_l for t in ["hypertension", "diabetes", "blood pressure", "vaginal delivery"]):
                    decision = "In-Cover"
                    treatment = f"{scheme_key} [{plan_key}] PMB Chronic / Maternal Benefit"
                else:
                    decision = "Requires Pre-Auth"
                    treatment = f"{scheme_key} [{plan_key}] Network Specialist & Inpatient Pre-Auth Required ({spec})"

            else:
                # Comprehensive / Top-Tier Plans: Broad GP & Specialist consults in-cover; inpatient surgeries & advanced imaging require Pre-Auth
                if any(t in desc_l for t in ["upper respiratory", "cold", "flu", "sore throat", "normal physical exam", "well child", "hypertension", "diabetes", "blood pressure", "vaginal delivery", "ent exam"]):
                    decision = "In-Cover"
                    treatment = f"{scheme_key} [{plan_key}] Comprehensive Primary Care Benefit"
                elif any(t in desc_l for t in ["mri", "ct scan", "surgery", "biopsy", "laparoscopy", "pacemaker", "resection", "arthroscopy"]):
                    decision = "Requires Pre-Auth"
                    treatment = f"{scheme_key} [{plan_key}] Major Inpatient / Advanced Radiology Pre-Auth Required ({spec})"
                elif spec_l in ["office notes", "general medicine", "pediatrics - neonatal", "ent - otolaryngology"]:
                    decision = "In-Cover"
                    treatment = f"{scheme_key} [{plan_key}] Comprehensive Specialist Consultation Benefit"
                else:
                    decision = "Requires Pre-Auth"
                    treatment = f"{scheme_key} [{plan_key}] Inpatient Specialist Procedural Pre-Auth ({spec})"

    # Generate SA Context Metadata
    province = random.choice(list(SA_PROVINCIAL_SUBURBS.keys()))
    suburb = random.choice(SA_PROVINCIAL_SUBURBS[province])
    demo_str, gender = random.choice(PATIENT_DEMOGRAPHICS)
    facility = random.choice(SA_HOSPITAL_NETWORKS)

    lang_key = random.choice(list(SA_GREETINGS.keys()))
    greeting = random.choice(
        SA_GREETINGS[lang_key] if lang_key == "Urban_Slang"
        else SA_GREETINGS[lang_key]["singular"] + SA_GREETINGS[lang_key]["plural"]
    )
    exclamation = random.choice(SA_EXCLAMATIONS)
    pain_str, pain_score = random.choice(SA_PAIN_DESCRIPTIONS)

    sa_header = (
        f"Claim Submission Context: {greeting}! {exclamation} "
        f"Medical Scheme & Plan Option: {plan_name}. "
        f"Facility: {facility} ({suburb}, {province.replace('_', ' ')}). "
        f"Patient Profile: {demo_str} (Reported Pain/Severity: {pain_score}/10 - {pain_str})."
    )

    return pd.Series([
        treatment, decision, scheme_key, plan_key, plan_name,
        province, suburb, facility, demo_str, gender, pain_score, sa_header
    ])

