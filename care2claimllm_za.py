def parse_scheme_and_claim_info(dialogue_history: str, triage_response: str) -> dict:
    """
    Extracts clinical scheme metadata, plan, and procedure details
    from dialogue history and triage guidance.
    """
    # Standardize text for extraction
    full_text = f"{dialogue_history}\n{triage_response}"

    # 1. Scheme & Plan Extraction (with sensible defaults for SA schemes)
    scheme_match = re.search(r"(Discovery|Fedhealth|Bonitas|Momentum|Medihelp)", full_text, re.IGNORECASE)
    scheme = scheme_match.group(1) if scheme_match else "Discovery Health"

    plan_match = re.search(r"(KeyCare|flexiFED|Classic|Saver|Access|Essential)", full_text, re.IGNORECASE)
    plan = plan_match.group(1) if plan_match else "Standard Option"

    # 2. Extract clinical scenario / symptoms
    symptom_match = re.search(r"(chest pain|cough|fever|headache|fracture|appendicitis|consultation|scans|mri)", full_text, re.IGNORECASE)
    clinical_scenario = symptom_match.group(0) if symptom_match else "General medical consultation and assessment"

    return {
        "scheme": scheme,
        "plan": plan,
        "clinical_scenario": clinical_scenario
    }

