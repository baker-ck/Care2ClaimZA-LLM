def extract_dialogue_pair(record: dict) -> Tuple[str, str]:
    """
    Extracts formatted input prompt history (Turns 1 to 3) and target
    assistant administrative triage guidance (Turn 4) from a Task 1 conversation record.
    """
    if "messages" in record and isinstance(record["messages"], list):
        messages = record["messages"]
        history_parts = []
        # Format Turns 1 through N-1 as dialogue history
        for msg in messages[:-1]:
            role = "user" if msg.get("role") in ["user", "system"] else "model"
            content = msg.get("content", "")
            history_parts.append(f"{SOT}{role}\n{content}{EOT}")
        prompt_history = "\n".join(history_parts)
        target_response = messages[-1].get("content", "")
        return prompt_history, target_response
    elif "input" in record and "output" in record:
        return f"{SOT}user\n{record['input']}{EOT}", str(record["output"])
    elif "prompt" in record and "response" in record:
        return f"{SOT}user\n{record['prompt']}{EOT}", str(record["response"])
    else:
        return "", ""

def format_io_as_turns(input_prompt: str, target_output: str) -> Tuple[str, str]:
    """
    Formats the dialogue history and target output into KerasNLP user/model turns.
    """
    formatted_q = input_prompt.strip() + "\n" if not input_prompt.endswith("\n") else input_prompt
    formatted_a = f"{SOT}model\n{target_output}{EOT}" if not target_output.startswith(SOT) else target_output
    return formatted_q, formatted_a

