def evaluate_nlg_performance(df_input: pd.DataFrame, title: str) -> dict:
    """Computes ROUGE-1, ROUGE-2, ROUGE-L, BLEU-2, and Semantic Cosine Similarity."""
    df_eval = df_input.copy()

    references = [extract_target_text(row.to_dict()) for _, row in df_eval.iterrows()]
    hypotheses = [clean_generated_text(row["model_output"]) for _, row in df_eval.iterrows()]

    r1_scores, r2_scores, rl_scores = [], [], []
    bleu_scores = []

    for ref, hyp in zip(references, hypotheses):
        # ROUGE
        scores = r_scorer.score(ref, hyp)
        r1_scores.append(scores['rouge1'].fmeasure)
        r2_scores.append(scores['rouge2'].fmeasure)
        rl_scores.append(scores['rougeL'].fmeasure)

        # BLEU-2
        ref_tokens = nltk.word_tokenize(ref.lower())
        hyp_tokens = nltk.word_tokenize(hyp.lower())
        bleu = sentence_bleu([ref_tokens], hyp_tokens, weights=(0.5, 0.5, 0, 0), smoothing_function=smooth_fn)
        bleu_scores.append(bleu)

    # Semantic Cosine Similarity
    if embedder is not None:
        ref_emb = embedder.encode(references)
        hyp_emb = embedder.encode(hypotheses)
        sims = np.diag(cosine_similarity(ref_emb, hyp_emb))
    else:
        vectorizer = TfidfVectorizer().fit(references + hypotheses)
        sims = [cosine_similarity(vectorizer.transform([r]), vectorizer.transform([h]))[0][0]
                for r, h in zip(references, hypotheses)]

    mean_r1 = np.mean(r1_scores)
    mean_r2 = np.mean(r2_scores)
    mean_rl = np.mean(rl_scores)
    mean_bleu = np.mean(bleu_scores)
    mean_sim = np.mean(sims)

    print(f"\n--- {title} ---")
    print(f"ROUGE-1 (Unigram Overlap)   : {mean_r1:.4f}")
    print(f"ROUGE-2 (Bigram Overlap)    : {mean_r2:.4f}")
    print(f"ROUGE-L (Longest Sequence)  : {mean_rl:.4f}")
    print(f"BLEU-2 (Precision Metric)   : {mean_bleu:.4f}")
    print(f"Semantic Cosine Similarity  : {mean_sim:.4f}")

    return {
        "rouge1": mean_r1,
        "rouge2": mean_r2,
        "rougeL": mean_rl,
        "bleu2": mean_bleu,
        "semantic_sim": mean_sim,
    }

